const sleep = (s) => new Promise(r => setTimeout(r, s * 1000));
const tabs = await listTabs();
let tab = (tabs.tabs || []).find(t => /bilibili\.com/.test(t.url || ""));
if (!tab) { await createTab("https://www.bilibili.com"); await sleep(4); }
// CDP 拿全部 cookies
const res = await cdp("Network.getAllCookies");
const cookies = (res.cookies || []).filter(c => /bilibili\.com$|\.bilibili\.com$/.test(c.domain));
console.log("B站 cookies 数量:", cookies.length);
// 登录态校验:三个关键 cookie 任一缺失都说明当前 profile 未登录,
// 导出的文件会让 yt-dlp 以游客身份下载(会员视频/高清流拿不到)。
const keys = ["SESSDATA", "bili_jct", "DedeUserID"];
const missing = keys.filter(n => !cookies.some(c => c.name === n));
console.log("关键 cookie:", keys.map(n => n + "=" + !missing.includes(n)).join(", "));
if (missing.length === keys.length) {
  console.log("!! 未检测到任何登录 cookie:请先在 ego lite 浏览器内登录 B站,再重新运行本脚本。");
} else if (missing.length > 0) {
  console.log("!! 缺少关键 cookie: " + missing.join(", ") + "(登录可能不完整,建议重新登录后再导出)");
}
// 生成 Netscape 格式 cookies.txt
const lines = ["# Netscape HTTP Cookie File", "# Generated by ego lite cookie export"];
for (const c of cookies) {
  const domain = c.domain;
  const flag = c.domain.startsWith(".") ? "TRUE" : "FALSE";
  const path = c.path || "/";
  const secure = c.secure ? "TRUE" : "FALSE";
  const expires = c.expires && c.expires > 0 ? Math.floor(c.expires) : "2147483647";
  lines.push([domain, flag, path, secure, expires, c.name, c.value].join("\t"));
}
await import("fs").then(fs => fs.default.writeFileSync("D:/bilibili/bili-cookies.txt", lines.join("\n") + "\n"));
console.log("已写入 D:/bilibili/bili-cookies.txt" + (missing.length ? "(注意:登录态不完整)" : ""));
